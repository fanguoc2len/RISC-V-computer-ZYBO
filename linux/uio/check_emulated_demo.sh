#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
demo_bin="${script_dir}/accel_mmio_demo"
run_bin="$(mktemp)"
log_file="$(mktemp)"
pbm_file="$(mktemp --suffix=.pbm)"
cleanup() {
    rm -f "${run_bin}" "${log_file}" "${pbm_file}" "${pbm_file}.umem.pbm" "${pbm_file}.cmdq.pbm"
}
trap cleanup EXIT

cp "${demo_bin}" "${run_bin}"
chmod +x "${run_bin}"
"${run_bin}" --emulate --pbm "${pbm_file}" >"${log_file}"

grep -q "backend         = emulated-mmio" "${log_file}"
grep -q "id_version      = 0x5a37100a" "${log_file}"
grep -q "npu_status_word = 0x4e000108" "${log_file}"
grep -q "npu_status_word = 0x4e010108" "${log_file}"
grep -q "npu_status_word = 0x4e008008" "${log_file}"
grep -q "npu_status_word = 0x4e018008" "${log_file}"
grep -q "umem_ctrl       = 0x00000007" "${log_file}"
grep -q "umem_status_word = 0x4e008008" "${log_file}"
grep -q "umem_logit0      = 20" "${log_file}"
grep -q "umem_gpu_row02  = 0x000007fc" "${log_file}"
grep -q "cmdq_status     = 0x00030004" "${log_file}"
grep -q "cmdq_tail_dbg   = 0x00000003" "${log_file}"
grep -q "cmdq_status_dbg = 0x00030004" "${log_file}"
grep -q "cmdq_fetch_off  = 0x00002040" "${log_file}"
grep -q "cmdq_fetch_seq  = 0x00000002" "${log_file}"
grep -q "cmdq_fetch_slot = 0x00000002" "${log_file}"
grep -q "cmdq_axi_status = 0x00000004" "${log_file}"
grep -q "cmdq_axi_araddr = 0x10002040" "${log_file}"
grep -q "cmdq_axi_seq    = 0x00000002" "${log_file}"
grep -q "cmdq_axi_beats  = 8" "${log_file}"
grep -q "cmdq_axi_desc0  = 0x00000001" "${log_file}"
grep -q "cmdq_dispatch_status = 0x00000004" "${log_file}"
grep -q "cmdq_dispatch_opcode = 0x00000001" "${log_file}"
grep -q "cmdq_dispatch_npu    = 1" "${log_file}"
grep -q "cmdq_dispatch_gpu    = 2" "${log_file}"
grep -q "cmdq_dispatch_err    = 0" "${log_file}"
grep -q "cmdq_npu_exec_status = 0x00018004" "${log_file}"
grep -q "cmdq_npu_exec_in     = 0x00000400" "${log_file}"
grep -q "cmdq_npu_exec_out    = 0x00000480" "${log_file}"
grep -q "cmdq_desc2      = 0x80000080" "${log_file}"
grep -q "cmdq_status_word = 0x4e008008" "${log_file}"
grep -q "cmdq_gpu_row02  = 0x000007fc" "${log_file}"
grep -q "gpu_pixels      = 45" "${log_file}"
grep -q "gpu_area2       = 64" "${log_file}"
grep -q "gpu_bbox        = 0x0a0a0202" "${log_file}"
grep -q "^P1$" "${pbm_file}"
grep -q "^32 32$" "${pbm_file}"
grep -q "^P1$" "${pbm_file}.umem.pbm"
grep -q "^32 32$" "${pbm_file}.umem.pbm"
grep -q "^P1$" "${pbm_file}.cmdq.pbm"
grep -q "^32 32$" "${pbm_file}.cmdq.pbm"

echo "PASS: emulated accel_mmio_demo regression completed."
